// Builds the main fonts and CSS of line-awesome from font-source/ (the 1.3.0 TrueType fonts),
// svg/ and added-icons.json: the glyphs of icons added after 1.3.0 are appended to copies of the
// 1.3.0 fonts and their classes to the end of the CSS. Same input, same bytes out.
//
//   node scripts/build-font.mjs           write dist/line-awesome/fonts/*.{ttf,woff,woff2} and the CSS block
//   node scripts/build-font.mjs --check   fail if dist differs from a fresh build
//
// The .eot and .svg fonts (legacy Internet Explorer) are not rebuilt: they have no added icons.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { Readable } from 'node:stream';
import { fileURLToPath } from 'node:url';
import { SVGIcons2SVGFontStream } from 'svgicons2svgfont';
import svg2ttf from 'svg2ttf';
import ttf2woff from 'ttf2woff';
import wawoff2 from 'wawoff2';
import { readAdditions } from './additions.mjs';
import { appendGlyphs, readCmap, readGlyphs } from './ttf-splice.mjs';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));

export const SOURCE_DIR = 'font-source/1.3.0';
export const FONTS_DIR = 'dist/line-awesome/fonts';
export const CSS_FILES = ['dist/line-awesome/css/line-awesome.css', 'dist/line-awesome/css/line-awesome.min.css'];
// Everything from this comment to the end of each CSS file is generated; the part before it is 1.3.0.
export const CSS_MARKER = '/* line-awesome: icons added after 1.3.0 (generated by scripts/build-font.mjs) */';
export const FONT_OF_STYLE = { solid: 'la-solid-900', brands: 'la-brands-400', regular: 'la-regular-400' };
export const FONT_NAMES = Object.values(FONT_OF_STYLE);

// Same metrics as the 1.3.0 fonts: 32 px of the svg grid are 1024 units, baseline at 28 px.
function svgFont(root, icons) {
  return new Promise((resolve, reject) => {
    const stream = new SVGIcons2SVGFontStream({ fontName: 'la-additions', fontId: 'la-additions', fontHeight: 1024, descent: 128, log: () => {} });
    let out = '';
    stream.on('data', (chunk) => (out += chunk)).on('end', () => resolve(out)).on('error', reject);
    for (const icon of icons) {
      const glyph = Readable.from([readFileSync(join(root, 'svg', icon.file))]);
      glyph.metadata = { name: icon.base, unicode: [String.fromCodePoint(parseInt(icon.codepoint, 16))] };
      stream.write(glyph);
    }
    stream.end();
  });
}

// The added icons drawn from svg/ as a TrueType font of their own, in the order of added-icons.json.
export async function drawFont(root, icons) {
  // A fixed timestamp keeps the font byte-identical between builds.
  return Buffer.from(svg2ttf(await svgFont(root, icons), { ts: 0, version: '1.0' }).buffer);
}

// Their glyphs as raw TrueType records, by class name.
async function drawGlyphs(root, icons) {
  const ttf = await drawFont(root, icons);
  const cmap = readCmap(ttf);
  const glyphs = readGlyphs(ttf);
  return new Map(icons.map((icon) => [icon.base, glyphs[cmap.get(parseInt(icon.codepoint, 16))]]));
}

export function cssBase(text) {
  const at = text.indexOf(CSS_MARKER);
  return at === -1 ? text : text.slice(0, at);
}

function cssBlock(icons, min) {
  const rules = icons.map((icon) => (min ? `.la-${icon.base}:before{content:"\\${icon.codepoint}"}` : `.la-${icon.base}:before {\n  content: "\\${icon.codepoint}"; }\n`));
  return min ? `${CSS_MARKER}\n${rules.join('')}\n` : `${CSS_MARKER}\n\n${rules.join('\n')}`;
}

export async function buildFont(root = repoRoot) {
  const icons = readAdditions(root);
  for (const icon of icons) if (!existsSync(join(root, 'svg', icon.file))) throw new Error(`missing svg/${icon.file}`);
  const glyphs = await drawGlyphs(root, icons);
  const files = {};
  for (const [style, name] of Object.entries(FONT_OF_STYLE)) {
    const base = readFileSync(join(root, SOURCE_DIR, `${name}.ttf`));
    const added = icons.filter((icon) => icon.style === style);
    // A font without new icons stays the 1.3.0 file, with its woff and woff2.
    if (!added.length) {
      files[`${FONTS_DIR}/${name}.ttf`] = base;
      continue;
    }
    const ttf = appendGlyphs(base, added.map((icon) => ({ codepoint: parseInt(icon.codepoint, 16), name: icon.base, glyph: glyphs.get(icon.base) })));
    files[`${FONTS_DIR}/${name}.ttf`] = ttf;
    files[`${FONTS_DIR}/${name}.woff`] = Buffer.from(ttf2woff(ttf).buffer);
    files[`${FONTS_DIR}/${name}.woff2`] = Buffer.from(await wawoff2.compress(ttf));
  }
  for (const file of CSS_FILES) {
    const min = file.endsWith('.min.css');
    files[file] = Buffer.from(cssBase(readFileSync(join(root, file), 'utf8')) + cssBlock(icons, min));
  }
  return files;
}

export async function staleFiles(root = repoRoot) {
  const files = await buildFont(root);
  return Object.entries(files)
    .filter(([file, bytes]) => !existsSync(join(root, file)) || !readFileSync(join(root, file)).equals(bytes))
    .map(([file]) => file);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === '--check') {
    const stale = await staleFiles();
    for (const file of stale) console.log(`out of date: ${file}`);
    console.log(stale.length ? 'run npm run build:font' : 'fonts and CSS match font-source/, svg/ and added-icons.json');
    process.exitCode = stale.length ? 1 : 0;
  } else {
    for (const [file, bytes] of Object.entries(await buildFont())) {
      writeFileSync(join(repoRoot, file), bytes);
      console.log(`${file}: ${bytes.length} bytes`);
    }
  }
}
